import random # підключаємо модуль випадкових чисел

solution = random.randint(1, 100) # загадуємо число від 1 до 100 включно

while True: # повторюємо введення, доки користувач не вгадає
    try:
        guess = int(input("Вгадай число від 1 до 100: ")) # зчитуємо ціле число
    except ValueError:
        print("Вводь число без ком чи крапок.")
        continue # після помилки повертаємося до введення

    if guess == solution: # перевіряємо правильну відповідь
        print("Вітаю! Ти зробив це, просто красава!")
        break # завершуємо цикл і гру
    elif guess > solution: # введене число завелике
        print("Завелике, використай Силу! Спробуй менше число.")
    else: # введене число замале
        print("Замале, але Сила тече в тобі та ти єдиний із Силою! Спробуй більше число.")