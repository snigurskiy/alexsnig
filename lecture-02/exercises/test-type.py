# 1. ЗМІННІ ТА ДИНАМІЧНА ТИПІЗАЦІЯ
# = присвоює значення; type() визначає тип об’єкта.
var1 = "My String"  # Змінна посилається на рядок (str).
print(type(var1))  # <class 'str'>
var1 = 100  # Тепер та сама змінна посилається на ціле число (int).
print(type(var1))  # <class 'int'>
print(var1 + 50)  # 150. Вираз не змінює var1: у ній залишається 100.
# Щоб зберегти суму у змінній, потрібно: var1 = var1 + 50.

# 2. ТИПИ ТА ЛОГІЧНІ ЗНАЧЕННЯ
print(type(int))  # <class 'type'>: int сам є об’єктом, який представляє тип.
print(type(str))  # <class 'type'>: str також представляє тип.
print(type(True))  # <class 'bool'>: логічне значення «істина».
print(int(True))  # 1: перетворення True на ціле число.
# Двійкові записи нижче — лише коментарі, а не команди:
# 00000001 — 1
# 00000000 — 0
# 00000010 — 2
# 00000011 — 3
print(int(False))  # 0: перетворення логічної «хиби» на ціле число.

# 3. СИСТЕМИ ЧИСЛЕННЯ
# Префікси визначають спосіб запису, але всі значення нижче мають тип int.
print(type(10))  # <class 'int'>: десятковий запис числа 10.
print(type(0o10))  # <class 'int'>: вісімковий запис, значення — 8.
print(type(0x10))  # <class 'int'>: шістнадцятковий запис, значення — 16.
print(isinstance(1, int))  # True: перевіряємо, чи належить 1 до типу int.
# type(значення) повідомляє тип; isinstance(значення, тип) перевіряє його.

# 4. ВЕЛИКІ ЧИСЛА ТА ПЕРЕТВОРЕННЯ НА ЦІЛЕ
a = 10_000_000_000  # Підкреслення лише полегшують читання числа.
print(a)  # 10000000000: підкреслення не друкуються.
x = 12.77  # Дійсне число типу float.
print(int(x))  # 12: int() відкидає дробову частину, а не округлює.
# Наприклад, int(-12.77) дає -12: відкидання відбувається в бік нуля.
print(7 ** 4300)  # ** — степінь; друкуємо велике ціле число з 3634 цифр.

# 5. ОСОБЛИВОСТІ FLOAT
# float зберігає числа у двійковому вигляді з обмеженою точністю.
# Дроби 0.1 і 0.2 у цьому форматі представлені наближено.
x = 0.1 + 0.2  # Маленька похибка стає видимою під час друку.
print(x)  # 0.30000000000000004
x = 0.1 + 0.1  # Тут стандартний короткий запис приховує наближеність.
print(x)  # 0.2; це не означає, що float зберігає десятковий дріб точно.

# 6. ДЕСЯТКОВА АРИФМЕТИКА DECIMAL
from decimal import Decimal, getcontext  # Імпортуємо тип і налаштування.
# Створюємо Decimal із тексту, щоб не переносити похибку float.
# Decimal("0.1") — точне значення, а Decimal(0.1) отримує наближений float.
x = Decimal("0.1") + Decimal("0.2")  # Додаємо точні десяткові значення.
print(x)  # 0.3
getcontext().prec = 4  # 4 значущі цифри загалом, НЕ 4 знаки після крапки.
# Налаштування діє на наступні обчислення Decimal, доки його не змінити.
price = Decimal("19.99")  # Створюємо десяткове значення ціни.
qty = Decimal("3")  # Створюємо десяткове значення кількості.
total = price * qty  # Множимо ціну на кількість.
print(total)  # 59.97: тут чотири значущі цифри — 5, 9, 9, 7.

# 7. ОБ’ЄДНАННЯ ТА ПОВТОРЕННЯ РЯДКІВ
hello = "Hello"  # Перший рядок.
world = "World"  # Другий рядок.
print(hello + " " + world)  # Hello World: + об’єднує рядки (конкатенація).
# " " містить один пробіл; без нього вийшло б HelloWorld.
print(hello[0] * 100)  # [0] отримує H, а * 100 повторює її сто разів.

# 8. ІНДЕКСИ: ВІДЛІК ПОЧИНАЄТЬСЯ З НУЛЯ
# Символи: H e l l o
# Індекси: 0 1 2 3 4
print(hello[0])  # H — перший символ.
print(hello[1])  # e — другий символ.
print(hello[2])  # l — третій символ.
print(hello[3])  # l — четвертий символ.
print(hello[4])  # o — п’ятий символ.
test = "Hello World"  # Пробіл також є символом: його індекс — 5.
print("_" * 100)  # Сто підкреслень як візуальний розділювач.

# 9. ЗРІЗИ: РЯДОК[ПОЧАТОК:КІНЕЦЬ]
# Початковий індекс включається, кінцевий — не включається.
print(test[0:5])  # Hello: беремо індекси 0, 1, 2, 3, 4.
print(test[:8])  # Hello Wo: початок пропущений, беремо індекси від 0 до 7.
# Щоб отримати llo, потрібен test[2:5], а не test[:8].

# 10. ПОДІЛ РЕЧЕННЯ НА СЛОВА
sentence = "Flat is better than nested"  # Задаємо речення.
words = sentence.split()  # Ділимо за пробільними символами на список слів.
# Без аргументів split() обробляє і кілька пробілів, і переноси рядка.
# Порожніх слів через кілька пробілів поспіль не виникає.
print(words)  # ['Flat', 'is', 'better', 'than', 'nested']
# Тепер words[0] — "Flat", а words[1] — "is".

# 11. ФОРМАТУВАННЯ ЧЕРЕЗ %
name, age = "John", 30  # Два присвоєння: name отримує "John", age — 30.
# %s — рядкове представлення; %d — ціле число.
# Значення з (name, age) підставляються у вказаному порядку.
print("Мене звати %s, мені %d років." % (name, age))
# Результат: Мене звати John, мені 30 років.
# Тут % форматує текст; із числами він може знаходити остачу від ділення.

# 12. ФОРМАТУВАННЯ ЧЕРЕЗ F-РЯДОК
n = 20  # Перший множник.
m = 25  # Другий множник.
prod = n * m  # Зберігаємо добуток 500.
# f перед лапками дозволяє підставляти значення через фігурні дужки.
print(f'The product of {n} and {m} is {prod}')
# Результат: The product of 20 and 25 is 500

# 13. КОДИ СИМВОЛІВ UNICODE
# ord() отримує один символ і повертає його числовий код.
# chr() отримує код і повертає відповідний символ.
# УВАГА: без print() ці виклики в .py-файлі нічого не виводять.
# Результат обчислюється, але не зберігається й не друкується.
ord('a')  # Повертає 97.
ord('#')  # Повертає 35.
ord('€')  # Повертає 8364.
ord('∑')  # Повертає 8721.
chr(97)  # Повертає 'a'.
chr(35)  # Повертає '#'.
chr(8364)  # Повертає '€'.
chr(8721)  # Повертає '∑'.
# Для показу результатів можна написати print(ord('a')) або print(chr(97)).

# 14. ОБРОБКА ПОМИЛКИ: TRY / EXCEPT
num1 = 100  # Ділене.
num2 = 0  # Дільник: ділити на нуль не можна.
# op == '/' — лише коментар. Без # це було б порівняння, не присвоєння.
# Для присвоєння використовують один знак =, для порівняння — два ==.
try:  # Пробуємо виконати блок, у якому може виникнути помилка.
    # До виклику print Python обчислює всі вставки у фігурних дужках.
    # 100 / 0 спричиняє ZeroDivisionError: цей print нічого не виведе.
    print(f"{num1} / {num2} = {num1 / num2}")
except ZeroDivisionError:  # Перехоплюємо саме помилку ділення на нуль.
    print("Error: Cannot divide by zero.")  # Виводимо пояснення помилки.
# Якщо num2 = 2, перший print виведе 100 / 2 = 50.0,
# а блок except буде пропущений, оскільки помилки немає.