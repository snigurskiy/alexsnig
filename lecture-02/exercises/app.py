"""Навчальні приклади: рядки, арифметика, функція та простий калькулятор.

Пояснення українською наведені безпосередньо біля відповідних команд.
Запуск у VS Code: Run Python File in Terminal.
Під час запуску потрібно ввести два цілі числа й одну операцію.
"""
# Потрійні лапки вище утворюють багаторядковий рядок.
# Оскільки він стоїть першою інструкцією файлу, це документація модуля
# (module docstring), а не звичайний коментар. Сам по собі він не друкується.
# У початковому коді _summary_, _type_ та _description_ були шаблонними
# позначками редактора: їх потрібно замінити змістовним описом або прибрати.
# Розділ Returns тут не потрібний: файл не є функцією з результатом return.

# comments — звичайний коментар. Усе після # до кінця рядка не виконується.
# Початковий коментар «This is a sample Python script...» означає:
# «Це приклад скрипту Python, який демонструє базові можливості».

# 1. РЯДОК І ВИВЕДЕННЯ
foo = "Hello, World!"  # Зберігаємо рядок у змінній foo через присвоєння =.
# foo — довільна назва змінної, а не спеціальна команда Python.
print(foo)  # Виводимо Hello, World! без лапок і переходимо на новий рядок.

# 2. ВІДНІМАННЯ
print(3 - 10000)  # -9997: від меншого числа віднімаємо більше.
print(10000 - 3)  # 9997: порядок операндів змінює результат віднімання.
# Python спочатку обчислює вираз у дужках, потім print виводить результат.

# 3. ВЛАСНА ФУНКЦІЯ
def add_numbers(a, b):  # def визначає функцію з двома параметрами a та b.
    """Отримує два числа та повертає їхню суму."""  # Документація функції.
    return a + b  # Обчислюємо суму, повертаємо її та завершуємо функцію.
# Двокрапка після заголовка починає блок функції.
# Відступ у 4 пробіли показує, які інструкції належать функції.
# Саме визначення функції ще не запускає її тіло.
# return не друкує результат: він передає його назад у місце виклику.

result = add_numbers(5, 3)  # Викликаємо функцію: a отримує 5, b отримує 3.
# Функція повертає 8, і це значення присвоюється змінній result.
# Параметри a та b всередині функції локальні: це окремі імена від a та b нижче.
print(result)  # 8: тепер явно друкуємо повернуте значення.

# 4. АРИФМЕТИКА З НАПЕРЕД ЗАДАНИМИ ЧИСЛАМИ
print("=== Simple Command-Line Calculator ===\n")  # Заголовок калькулятора.
# \n у кінці рядка додає перенесення. print також додає стандартне перенесення,
# тому після заголовка буде один порожній рядок.
a = b = 2  # Ланцюжок присвоєнь: і a, і b отримують значення 2.
print("a: ", a)  # Виводимо підпис і 2.
print("b: ", b)  # Виводимо підпис і 2.
# У підписах уже є кінцевий пробіл; print додає ще свій роздільник-пробіл.
# Тому після двокрапки фактично два пробіли. Це не помилка обчислень.
# Для одного пробілу можна писати print("a:", a).
print("a + b = ", a + b)  # 4: додавання.
print("a - b = ", a - b)  # 0: віднімання.
print("a * b = ", a * b)  # 4: множення; * означає «помножити».

# 5. ВВЕДЕННЯ ЧИСЕЛ
a = int(input("Enter a number: "))  # Запитуємо перше ціле число.
# input показує підказку та чекає Enter, а потім повертає введений текст.
# int перетворює текст на ціле число: наприклад, "15" стає 15.
# Нове присвоєння замінює попереднє значення a, яке було 2.
b = int(input("Enter another number: "))  # Аналогічно зчитуємо друге число.
# Текст, порожнє введення або запис "2.5" спричинять ValueError.
# Обробки неправильного введення у цьому прикладі немає: вводимо цілі числа.
print("a + b = ", a + b)  # Одразу друкуємо суму введених чисел.
# Цей рядок виконується ще ДО вибору операції, тому сума друкується завжди.
# Це не синтаксична помилка, але для звичайного калькулятора рядок можна
# прибрати, якщо потрібен лише результат вибраної операції.

# 6. ВИБІР ОПЕРАЦІЇ
operation = input("Enter an operation (+, -, *, /): ")  # Зчитуємо рядок.
# Наприклад, введений знак + зберігається як рядок "+".
# Пробіли не видаляються автоматично: " + " не дорівнює "+".
# За потреби можна додати .strip() після input(...) для крайніх пробілів.

if operation == "+":  # Якщо значення operation дорівнює рядку "+".
    print("Result: ", a + b)  # Виводимо суму.
elif operation == "-":  # Інакше перевіряємо, чи вибрано віднімання.
    print("Result: ", a - b)  # Виводимо різницю.
elif operation == "*":  # Інакше перевіряємо множення.
    print("Result: ", a * b)  # Виводимо добуток.
elif operation == "/":  # Інакше перевіряємо ділення.
    if b != 0:  # Усередині гілки ділення перевіряємо: b НЕ дорівнює нулю.
        print("Result: ", a / b)  # Ділимо, лише якщо дільник ненульовий.
        # / повертає float: наприклад, 6 / 3 дає 2.0.
    else:  # Цей else належить внутрішньому if b != 0.
        print("Error: Division by zero is not allowed.")  # Пояснюємо помилку.
        # a / b тут не виконується: перевірка запобігає ZeroDivisionError.
else:  # Цей else належить зовнішньому ланцюжку if / elif.
    print("Invalid operation. Please enter one of +, -, *, or /.")
    # Повідомляємо, що введений знак не збігся з жодною дозволеною операцією.

# ЯК ПРАЦЮЄ ЛАНЦЮЖОК УМОВ
# == порівнює значення, тоді як = присвоює значення змінній.
# != означає «не дорівнює».
# Умови перевіряються згори вниз. Виконується лише перша відповідна гілка.
# elif — це «інакше, якщо», а else — «інакше» без додаткової умови.
# Відступи визначають вкладеність: зовнішні гілки мають один рівень,
# а перевірка дільника всередині гілки / — ще один рівень.
# Порожні рядки між частинами програми додані лише для зручності читання.

# ПРИКЛАД: введення 10, 2, /.
# Спочатку приклади на початку файлу виведуть свої результати.
# Потім калькулятор після введення чисел покаже суму 12.
# Після введення / він додатково покаже Result:  5.0.
# Для 10, 0, / замість частки буде повідомлення про ділення на нуль.
# Для 10, 2, ? буде повідомлення про неправильну операцію.
# Циклу тут немає: після одного вибору операції програма завершується.
