# Зчитуємо перше число та перетворюємо його на ціле
a = int(input())

# Зчитуємо друге число та перетворюємо його на ціле
b = int(input())

# Виводимо суму, різницю, добуток, частку та a у степені b.
# sep='&' розділяє результати символом & без пробілів.
print(a + b, a - b, a * b, a / b, a ** b, sep='&')