# Функція переводить кілометри в милі.
def km_to_miles(km):
    # Зберігаємо коефіцієнт перетворення.
    coefficient = 0.621371

    # Множимо кілометри на коефіцієнт.
    miles = km * coefficient

    # Виводимо відстань у милях.
    print(miles)


# Зчитуємо відстань у кілометрах.
a = float(input("Введіть кількість кілометрів: "))

# Передаємо введене значення у функцію.
km_to_miles(a)