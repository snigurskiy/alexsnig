# Зчитуємо введені значення та перетворюємо їх на дійсні числа
num1 = float(input("Enter first number: "))
num2 = float(input("Enter second number: "))
num3 = float(input("Enter third number: "))
# Виводимо дійсне число
print(num1, num2, num3, sep='\n')
# Перетворюємо його на ціле та виводимо
print(int(num1, num2, num3, sep='\n'))