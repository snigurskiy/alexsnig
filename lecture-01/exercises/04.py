feet = int(input("Feet: ")) # вводимо фути, перетворюємо рядок на ціле число
inches = int(input("Inches: ")) # задаємо дюймам цілочисленне значення і запрошуємо їх ввести
height = round(feet * 30.48 + inches * 2.54) # переводимо висоту з футів і дюймів у сантиметри
print("Your Height Is:", height, "cm.") # виводимо за допомогою форматованого рядка значення висоти у сантиметрах