feet = int(input("Feet: ")) # задаємо футам цілочислений тип ізапрошуємо їх ввести
inches = int(input("Inches: ")) # задаємо дюймам цілочисленне значення і запрошуємо їх ввести
height = feet * 30.48 + inches * 2.54 # переводимо висоту з футів і дюймів у сантиметри
print(f"Your Height Is: {height} cm.") # виводимо за допомоою форматованого рядка значення висоти у сантиметрах